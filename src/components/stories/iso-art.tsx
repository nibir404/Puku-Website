"use client";

import { memo, useEffect, useRef, useState } from "react";
import { ISO_ART, type IsoArtName } from "@/lib/iso-art";

/** Groups whose children drop in one by one (cells of the P, slabs, racks, steps…). */
const BUILD = ["puku-p", "model-puku-ai", "racks", "steps", "credit-stack", "t"];

/**
 * Inline isometric illustration from scripts/iso-gen.py.
 * Colors come from --iso-* tokens, so it follows the theme toggle; motion lives in globals.css
 * and starts when the art scrolls into view. `active` highlights a named part (model / partner).
 */
export function IsoArt({ name, active, className = "", label }: { name: IsoArtName; active?: string; className?: string; label?: string }) {
  const ref = useRef<HTMLDivElement>(null);
  const [play, setPlay] = useState(false);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    el.querySelectorAll<SVGGElement>(".iso-svg > svg > g").forEach((g, i) => g.style.setProperty("--i", String(i)));
    el.querySelectorAll<SVGGElement>(BUILD.map((id) => `#${id}`).join(",")).forEach((g) => {
      g.setAttribute("data-build", "");
      Array.from(g.children).forEach((c, j) => (c as SVGElement).style.setProperty("--j", String(c.tagName === "g" ? j : Math.floor(j / 3))));
    });
    const io = new IntersectionObserver(([e]) => e.isIntersecting && (setPlay(true), io.disconnect()), { threshold: 0.25 });
    io.observe(el);
    return () => io.disconnect();
  }, [name]);

  return (
    <div ref={ref} role="img" aria-label={label ?? name} data-play={play ? "" : undefined} data-active={active} className={`iso ${className}`}>
      <Svg name={name} />
    </div>
  );
}

/* Memoized so state changes on the wrapper never re-apply the markup (which would drop --i / --j). */
const Svg = memo(function Svg({ name }: { name: IsoArtName }) {
  // Static, build-time SVG generated by our own script, never user input.
  return <div className="iso-svg" dangerouslySetInnerHTML={{ __html: ISO_ART[name] }} />;
});
